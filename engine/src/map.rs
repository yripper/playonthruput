//! 32×32 tile grids. 1 KB per level keeps collision and line-of-sight to a
//! handful of lookups, and levels compile into the binary as read-only data.

pub const MAP_W: usize = 32;
pub const MAP_H: usize = 32;
pub const MAX_SPAWNS: usize = 8;

pub const EMPTY: u8 = 0;
pub const BRICK: u8 = 1;
pub const STONE: u8 = 2;
pub const TECH: u8 = 3;

pub struct Level {
    tiles: [u8; MAP_W * MAP_H],
    /// Tile coordinates marked `S` (arena) or `P` (campaign start).
    spawns: [(i32, i32); MAX_SPAWNS],
    spawn_count: usize,
}

impl Level {
    /// Out-of-bounds reads as wall, so rays and movement can never leave the map.
    #[inline]
    pub fn tile(&self, x: i32, y: i32) -> u8 {
        if x < 0 || y < 0 || x >= MAP_W as i32 || y >= MAP_H as i32 {
            BRICK
        } else {
            self.tiles[y as usize * MAP_W + x as usize]
        }
    }

    pub fn spawns(&self) -> &[(i32, i32)] {
        &self.spawns[..self.spawn_count]
    }
}

const fn parse(rows: &[&str; MAP_H]) -> Level {
    let mut tiles = [EMPTY; MAP_W * MAP_H];
    let mut spawns = [(0, 0); MAX_SPAWNS];
    let mut spawn_count = 0;
    let mut y = 0;
    while y < MAP_H {
        let row = rows[y].as_bytes();
        assert!(row.len() == MAP_W, "every map row must be exactly 32 tiles");
        let mut x = 0;
        while x < MAP_W {
            tiles[y * MAP_W + x] = match row[x] {
                b'#' => BRICK,
                b'%' => STONE,
                b'@' => TECH,
                b'P' | b'S' => {
                    assert!(spawn_count < MAX_SPAWNS, "too many spawn points");
                    spawns[spawn_count] = (x as i32, y as i32);
                    spawn_count += 1;
                    EMPTY
                }
                _ => EMPTY,
            };
            x += 1;
        }
        y += 1;
    }
    assert!(spawn_count > 0, "a level needs at least one spawn");
    Level {
        tiles,
        spawns,
        spawn_count,
    }
}

